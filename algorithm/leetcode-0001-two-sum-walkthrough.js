// ═══════════════ Step 1 · 读题 + 造用例（5 分钟） ═══════════════
//
// 题目：给定整数数组 nums 和目标值 target，
//       找出和为 target 的两个整数，返回它们的数组下标。
//       （每个输入恰好有一个答案，同一个元素不能用两次）
//
// 合上题目，自己造 3 组测试数据（造不出来 = 没读懂，回去重读）：
//   ① 常规：    nums = [2, 7, 11, 15], target = 9  →  2+7=9   →  [0, 1]
//   ② 换位置：  nums = [3, 2, 4],      target = 6  →  2+4=6   →  [1, 2]
//   ③ 边界⚠️：  nums = [3, 3],         target = 6  →  3+3=6   →  [0, 1]
//                ↑ 两个数【值相同】但【下标不同】！很多解法在这里翻车，
//                  因为"3 已经用过了"不等于"另一个 3 不能用"
//
// ═══════════════ Step 2 · 独立思考（15–25 分钟，先别往下看！） ═══════════════
//
// 【你的思路区】现在合上文件，在纸上回答：
//   Q1: 最笨的方法怎么做？（两层 for 循环枚举所有数对，一个一个试）
//   Q2: 笨方法要试多少次？数组有 n 个数时大约 n²/2 次 —— 这就是 O(n²)
//   Q3: 哈希表（JS 里的 Map/对象）查找一个东西只要 1 步 O(1)，
//       能不能用它把"找另一半"变快？
//
// ─────────────────────────────────────────────
// 卡住 25 分钟以上？完全正常，往下看 ↓
// ─────────────────────────────────────────────
//
// 思路 A · 暴力解（保底方案，面试先说这个不丢人）：
//   外层循环拿起第一个数 nums[i]，
//   内层循环拿起它后面的每个数 nums[j]（从 i+1 开始），
//   加起来等于 target 就返回 [i, j]。
//   时间 O(n²) · 空间 O(1)
//
//   ↑ 为什么 j 从 i+1 开始，而不是 0？
//     一是不重复检查（1+2 和 2+1 是同一对）；
//     二是保证不会"同一个数用两次"。
//
// 思路 B · 哈希解（一句话点破）：
//   "站在每个数 x 的角度，我要找的其实是 target - x 这个【另一半】。
//    『判断某个值存不存在』并且要 O(1) —— 这就是哈希表的看家本领。"
//
//   所以只需一遍循环：
//   ① 走到数字 x 时，先问哈希表："target - x 在你那儿吗？"
//   ② 在 → 直接返回两个下标，游戏结束
//   ③ 不在 → 把 x 和它的下标记进哈希表，继续走
//   时间 O(n) · 空间 O(n)（用空间换时间，最经典的交易）

// ═══════════════ Step 3 · 两种解法代码 ═══════════════

// 解法 A · 暴力（先看懂这个）
function twoSumBrute(nums, target) {
  for (let i = 0; i < nums.length; i++) {          // 拿起第一个数
    for (let j = i + 1; j < nums.length; j++) {    // 拿起它后面的数
      if (nums[i] + nums[j] === target) {          // 加起来试试
        return [i, j];                              // 中了！返回两个下标
      }
    }
  }
  return []; // 题目保证有解，这行只是保底
}

// 解法 B · 哈希表一遍循环（面试的标准答案）
function twoSumHash(nums, target) {
  const seen = new Map(); // Map = JS 的哈希表：存 "数值 → 下标"
  for (let i = 0; i < nums.length; i++) {
    const x = nums[i];
    const partner = target - x;        // 我要找的"另一半"
    if (seen.has(partner)) {           // 另一半之前出现过？
      return [seen.get(partner), i];   // 返回 [另一半的下标, 我的下标]
    }
    seen.set(x, i);                    // 没找到 → 把自己登记进表，等别人来找我
  }
  return [];
}

// 动手验证：把 ①②③ 三组用例交给两个解法跑一遍
function test(name, fn) {
  const cases = [
    { nums: [2, 7, 11, 15], target: 9, expect: [0, 1] },
    { nums: [3, 2, 4], target: 6, expect: [1, 2] },
    { nums: [3, 3], target: 6, expect: [0, 1] }, // ← 边界用例，专治"用同一个数两次"
  ];
  let allPass = true;
  for (const c of cases) {
    const got = fn(c.nums, c.target);
    const pass = JSON.stringify(got) === JSON.stringify(c.expect);
    if (!pass) allPass = false;
    console.log(`${pass ? "✅" : "❌"} ${name} nums=[${c.nums}] target=${c.target} → [${got}]（期望 [${c.expect}]）`);
  }
  console.log(`${allPass ? "🎉" : "💥"} ${name} 测试${allPass ? "全部通过" : "存在失败"}\n`);
}

console.log("── 两数之和 · 双解法验证 ──\n");
test("暴力解", twoSumBrute);
test("哈希解", twoSumHash);

