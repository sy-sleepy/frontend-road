// ─────────────────────────────────────────
// 一、变量 = 贴了标签的盒子
// ─────────────────────────────────────────
// 用 let 声明"以后会变"的东西
let myGoal = "进大厂做前端";
console.log("我的目标：", myGoal);

// 盒子里的东西可以换（重新赋值）
myGoal = "15 周后拿到第一份实习";
console.log("细化后的目标：", myGoal);

// 用 const 声明"不会再变"的东西（const = constant，常量）
const school = "普通本科";
const grade = "大三";
console.log(`背景：${school} · ${grade}`); // ← 这是"模板字符串"，用反引号 ` 包起来，${} 里能放变量

// 试着取消下面两行的注释（删掉 //），跑一下看会发生什么：
// const 常量重新赋值会直接报错 —— 这是 JS 在保护你不犯低级错误
// school = "清华";
// console.log(school);

// ─────────────────────────────────────────
// 二、三种最常用的数据类型
// ─────────────────────────────────────────
let title = "前端工程师";        // string  字符串：用引号包起来
let weeks = 15;                  // number  数字：不加引号
let isDayOne = true;             // boolean 布尔：只有 true / false 两个值

console.log(`目标岗位：${title}（类型：${typeof title}）`);
console.log(`冲刺周期：${weeks} 周（类型：${typeof weeks}）`);
console.log(`今天是 Day 1 吗：${isDayOne}（类型：${typeof isDayOne}）`);
// typeof 能查看任何东西的类型 —— 不确定的时候，console.log(typeof xxx) 永远是你的朋友

// ─────────────────────────────────────────
// 三、字符串拼接：老方法 vs 新方法
// ─────────────────────────────────────────
const name = "未来的大厂工程师";
const oldWay = "你好，" + name + "！今天是第 " + 1 + " 天";   // 用 + 号拼，麻烦易错
const newWay = `你好，${name}！今天是第 ${1} 天`;              // 模板字符串，优雅
console.log(oldWay);
console.log(newWay);
// 记住：以后一律用反引号 `` + ${} 的写法

// ─────────────────────────────────────────
// 四、简单算术 —— JS 就是个计算器
// ─────────────────────────────────────────
const hoursPerDay = 3;           // 每天学 3 小时
const days = 7;                  // 每周 7 天... 不，休息日也得有
const restDay = 1;               // 每周休 1 天
const weeklyHours = hoursPerDay * (days - restDay);
console.log(`每周可投入：${weeklyHours} 小时`);
console.log(`15 周累计：${weeklyHours * 15} 小时 —— 这就是你和 0 的差距`);

